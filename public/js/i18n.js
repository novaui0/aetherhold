const STORAGE_KEY = "aetherhold.language.v1";
const listeners = new Set();

function detect() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && DICT[saved]) return saved;
  } catch { /* private mode */ }
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("tr")) return "tr";
  return "en";
}

export let language = detect();

export function t(key, vars = null) {
  const table = DICT[language] || DICT.en;
  let value = table[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function setLanguage(next, { silent = false } = {}) {
  if (!DICT[next] || next === language) return language;
  language = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* private mode */ }
  document.documentElement.lang = next === "tr" ? "tr" : "en";
  translateDom();
  if (!silent) listeners.forEach((fn) => fn(next));
  return language;
}

export function onLanguage(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function translateDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = t(node.dataset.i18nHtml);
  });
  const langSelect = document.getElementById("language-select");
  if (langSelect && langSelect.value !== language) langSelect.value = language;
}

export function mountLanguagePicker() {
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.language);
      document.querySelectorAll("[data-language]").forEach((other) => {
        other.classList.toggle("active", other.dataset.language === language);
      });
    });
    button.classList.toggle("active", button.dataset.language === language);
  });
  document.documentElement.lang = language === "tr" ? "tr" : "en";
  translateDom();
}
